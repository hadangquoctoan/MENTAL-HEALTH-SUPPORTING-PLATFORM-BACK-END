  "updated_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "doctor_assignments" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "doctor_id" bigint NOT NULL,
  "patient_id" bigint NOT NULL,
  "previous_assignment_id" bigint,
  "assigned_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "ended_at" timestamp NULL,
  "status" "doctor_assignments_status_enum" NOT NULL DEFAULT 'ACTIVE',
  "created_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "deleted_at" timestamp NULL,
  CONSTRAINT "chk_doctor_assignments_active_ended"
    CHECK (("status" = 'ACTIVE' AND "ended_at" IS NULL) OR "status" <> 'ACTIVE'),
  CONSTRAINT "chk_doctor_assignments_closed_ended"
    CHECK ("status" = 'ACTIVE' OR "ended_at" IS NOT NULL),
  CONSTRAINT "chk_doctor_assignments_dates"
    CHECK ("ended_at" IS NULL OR "assigned_at" <= "ended_at")
);

