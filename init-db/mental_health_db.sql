-- Tự cập nhật updated_at cả khi ghi dữ liệu trực tiếp bằng SQL.
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = statement_timestamp() AT TIME ZONE 'UTC';
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'action_logs',
    'chat_sessions',
    'check_ins',
    'doctor_assignments',
    'doctor_notes',
    'doctor_notifications',
    'doctor_profiles',
    'emergency_actions',
    'emergency_contacts',
    'emergency_events',
    'medications',
    'patient_profiles',
    'patient_streaks',
    'plans',
    'plan_actions',
    'reminder_logs',
    'screening_attempts',
    'screening_questions',
    'screening_results',
    'screening_types',
    'users'
  ]
  LOOP
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      'trg_' || tbl || '_updated_at',
      tbl
    );
  END LOOP;
END;
$$;

COMMIT;
